/** Gutenberg owns DOM IDs (block-<clientId>), so editor styles use root classes.
 * Generate from the frontend sources to keep both canvases in sync. No post edits.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import postcss from 'postcss';

const assets = path.join(import.meta.dirname, 'lenremont-page-importer/assets');
const files = ['reference-adapter.css', 'frontend.css', 'reference/original.css', 'canvas.css'];
let output = '@charset "UTF-8";\n/* Generated by wordpress-plugin/build-editor-styles.mjs. Editor only. */\n';
for (const file of files) {
  const css = postcss.parse(await fs.readFile(path.join(assets, file), 'utf8'));
  // Already loaded by the frontend stylesheets in the editor. Do not duplicate
  // font registration or change the names of animation keyframes.
  css.walkAtRules(rule => {
    if (/^(?:charset|font-face|(?:-webkit-)?keyframes)$/i.test(rule.name)) rule.remove();
  });
  css.walkRules(rule => {
    const selectors = rule.selectors.filter(selector => !selector.includes(':has('));
    if (!selectors.length) { rule.remove(); return; }
    rule.selectors = selectors.map(selector => {
      if (!selector.includes('#hop-gutenberg')) throw new Error(`Unscoped input in ${file}: ${selector}`);
      return '.editor-styles-wrapper ' + selector
        .replace(/^\.editor-styles-wrapper\s+/, '')
        .replaceAll('#hop-gutenberg.lr-reference', '.lr-reference')
        .replaceAll('#hop-gutenberg', ':is(.lr-reference, .lr-imported-page)');
    });
  });
  // Keep relative image URLs correct when moving original.css up one directory.
  if (file.startsWith('reference/')) {
    css.walkDecls(decl => {
      decl.value = decl.value.replace(/url\((["']?)(?!data:|https?:|\/|#)([^)'"\s]+)\1\)/g, 'url("reference/$2")');
    });
  }
  output += `\n/* ${file} */\n${css.toString()}\n`;
}
// Gutenberg may wrap an alignfull root in its own .wp-block in classic themes.
// Target only the immediate shell containing our landing, never other posts.
output += `\n.editor-styles-wrapper .is-root-container > .wp-block:has(> .lr-reference) {
  width: 100%; max-width: none; margin: 0;
}\n`;
await fs.writeFile(path.join(assets, 'editor-content.css'), output);
console.log('Generated editor-content.css for legacy and current Gutenberg pages.');
